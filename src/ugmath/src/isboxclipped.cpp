bool Clipper::IsBoxClipped(const double* const box, const ClipBounds& bounds,
                           int& status) {
    status = 0;
    if (!bounds.IsValid()) {
        status = 2;
        return false;
    }
    const int dim = bounds.dim;
    if (box[0] > box[dim] || box[1] > box[dim + 1] ||
        (dim == 3 && box[2] > box[5])) {
        status = 1;
        return false;
    }
    const int f = bounds.flags;
    for (int ix = 0; ix < dim + 1; ix += dim) {
        const double x = box[ix];
        for (int iy = 1; iy < dim + 2; iy += dim) {
            const double y = box[iy];
            const int zsteps = (dim == 3) ? 2 : 1;
            for (int s = 0, iz = 2; s < zsteps; ++s, iz += dim) {
                const double z = (dim == 3) ? box[iz] : 0.0;
                int code = 0;
                if ((f & 1) != 0 && x > bounds.d[0]) code = 1;
                if ((f & 2) != 0 && bounds.d[1] > x) code |= 2;
                if ((f & 4) != 0 && y > bounds.d[2]) code |= 4;
                if ((f & 8) != 0 && bounds.d[3] > y) code |= 8;
                if (dim == 3) {
                    if ((f & 0x10) != 0 && z > bounds.d[4]) code |= 0x10;
                    if ((f & 0x20) != 0 && bounds.d[5] > z) code |= 0x20;
                }
                if (code != 0) return true;
            }
        }
    }
    return false;
}

